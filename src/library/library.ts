const newId = () => `${Date.now().toString(36)}${Math.random().toString(36).slice(2, 8)}`;

export function parseFileName(name: string): { artist: string; title: string } {
  const base = name
    .replace(/\.[a-z0-9]{2,5}$/i, '')
    .replace(/_/g, ' ')
    .replace(/^\d{1,3}[\s.\-_]+/, '')
    .trim();
  const parts = base.split(/\s+[-–—]\s+/);
  if (parts.length >= 2) return { artist: parts[0].trim(), title: parts.slice(1).join(' - ').trim() };
  return { artist: '', title: base };
}

const waveformCache = new Map<string, Waveform>();

export async function getWaveform(id: string): Promise<Waveform | null> {
  const cached = waveformCache.get(id);
  if (cached) return cached;
  const w = await loadJSON<Waveform>(id);
  if (w) waveformCache.set(id, w);
  return w;
}

async function analyzeTrack(id: string, bytes: ArrayBuffer | undefined, fileName: string) {
  const ctx = getEngine().ctx;
  const buffer = await ctx.decodeAudioData(bytes ?? (await readAudio(id)));
  const channels: Float32Array[] = [];
  for (let c = 0; c < Math.min(2, buffer.numberOfChannels); c++) channels.push(buffer.getChannelData(c));
  const { analysis, waveform } = await analyzeChannels(channels, buffer.sampleRate);
  waveformCache.set(id, waveform);
  await saveJSON(id, waveform);
  return { ...analysis, bpm: applyBpmHint(analysis.bpm, fileName) };
}

export const useLibrary = create<LibraryState>()(
  persist(
    (set, get) => ({
      tracks: [],
      crates: [],
      cues: {},
      progress: null,

      pickAndImport: async (opts) => {
        const res = await DocumentPicker.getDocumentAsync({
          type: ['audio/*'],
          multiple: !opts?.spotifyId,
          copyToCacheDirectory: true,
        });
        if (res.canceled || !res.assets?.length) return [];
        return get().importPicked(
          res.assets.map((a) => ({ uri: a.uri, name: a.name, file: (a as { file?: Blob }).file })),
          opts,
        );
      },

      importPicked: async (files, opts) => {
        const added: Track[] = [];
        set({ progress: { total: files.length, done: 0, current: '' } });
        try {
          for (const f of files) {
            const id = newId();
            const { artist, title } = parseFileName(f.name);
            set((s) => ({ progress: { ...s.progress!, current: title } }));
            await saveAudio(id, f);
            let track: Track = {
              id,
              title,
              artist,
              fileName: f.name,
              addedAt: Date.now(),
              spotifyId: opts?.spotifyId,
              analyzed: false,
              bpm: 0,
              firstBeat: 0,
              key: '',
              camelot: '',
              duration: 0,
            };
            set((s) => ({ tracks: [track, ...s.tracks] }));
            try {
              const analysis = await analyzeTrack(id, undefined, f.name);
              track = { ...track, ...analysis, analyzed: true };
            } catch (e) {
              console.warn('analysis failed', f.name, e);
            }
            set((s) => ({
              tracks: s.tracks.map((t) => (t.id === id ? track : t)),
              progress: { ...s.progress!, done: s.progress!.done + 1 },
            }));
            added.push(track);
          }
        } finally {
          set({ progress: null });
        }
        return added;
      },

      removeTrack: async (id) => {
        await deleteAudio(id);
        waveformCache.delete(id);
        set((s) => {
          const cues = { ...s.cues };
          delete cues[id];
          return {
            tracks: s.tracks.filter((t) => t.id !== id),
            cues,
            crates: s.crates.map((c) => ({
              ...c,
              entries: c.entries.map((e) => (e.trackId === id ? { ...e, trackId: undefined } : e)),
            })),
          };
        });
      },

      updateTrack: (id, patch) => {
        set((s) => ({ tracks: s.tracks.map((t) => (t.id === id ? { ...t, ...patch } : t)) }));
        const t = get().tracks.find((x) => x.id === id);
        if (t) getEngine().refreshTrack(t);
      },

      saveCrate: (crate) =>
        set((s) => ({ crates: [crate, ...s.crates.filter((c) => c.id !== crate.id)] })),

      removeCrate: (id) => set((s) => ({ crates: s.crates.filter((c) => c.id !== id) })),

      setCues: (trackId, cues) => set((s) => ({ cues: { ...s.cues, [trackId]: cues } })),

      cacheLimitMB: 1024,
      setCacheLimit: (cacheLimitMB) => {
        set({ cacheLimitMB });
        get().enforceCache();
      },

      importFromDrive: async (files) => {
        const added: Track[] = [];
        const known = new Set(get().tracks.map((t) => t.driveFileId).filter(Boolean));
        const todo = files.filter((f) => !f.isFolder && !known.has(f.id));
        set({ progress: { total: todo.length, done: 0, current: '' } });
        try {
          for (const f of todo) {
            const id = newId();
            const { artist, title } = parseFileName(f.name);
            set((s) => ({ progress: { ...s.progress!, current: title } }));
            const bytes = await downloadFile(f.id);
            // decoding transfers/detaches the buffer on some platforms: store a copy first
            await saveAudioBytes(id, bytes.slice(0));
            let track: Track = {
              id,
              title,
              artist,
              fileName: f.name,
              addedAt: Date.now(),
              analyzed: false,
              bpm: 0,
              firstBeat: 0,
              key: '',
              camelot: '',
              duration: 0,
              driveFileId: f.id,
              size: f.size || bytes.byteLength,
              cached: true,
              lastUsed: Date.now(),
            };
            set((s) => ({ tracks: [track, ...s.tracks] }));
            try {
              track = { ...track, ...(await analyzeTrack(id, bytes, f.name)), analyzed: true };
            } catch (e) {
              console.warn('analysis failed', f.name, e);
            }
            set((s) => ({
              tracks: s.tracks.map((t) => (t.id === id ? track : t)),
              progress: { ...s.progress!, done: s.progress!.done + 1 },
            }));
            added.push(track);
            // keep the cache under budget while importing a whole folder
            await get().enforceCache();
          }
        } finally {
          set({ progress: null });
        }
        return added;
      },

      ensureAudio: async (track) => {
        const now = Date.now();
        const current = get().tracks.find((t) => t.id === track.id) ?? track;
        if (current.driveFileId && !current.cached) {
          const bytes = await downloadFile(current.driveFileId);
          await saveAudioBytes(current.id, bytes);
          get().updateTrack(current.id, { cached: true, size: bytes.byteLength, lastUsed: now });
          await get().enforceCache();
        } else {
          set((s) => ({ tracks: s.tracks.map((t) => (t.id === track.id ? { ...t, lastUsed: now } : t)) }));
        }
      },

      enforceCache: async () => {
        const limit = get().cacheLimitMB * 1024 * 1024;
        const onDecks = new Set(getEngine().decks.map((d) => d.track?.id).filter(Boolean));
        const cached = get().tracks.filter((t) => t.driveFileId && t.cached);
        let used = cached.reduce((sum, t) => sum + (t.size ?? 0), 0);
        // least recently used first; never evict what is loaded on a deck
        const victims = cached.filter((t) => !onDecks.has(t.id)).sort((a, b) => (a.lastUsed ?? 0) - (b.lastUsed ?? 0));
        for (const t of victims) {
          if (used <= limit) break;
          await deleteAudioFile(t.id);
          used -= t.size ?? 0;
          set((s) => ({ tracks: s.tracks.map((x) => (x.id === t.id ? { ...x, cached: false } : x)) }));
        }
      },

      importDemo: async () => {
        const have = new Set(get().tracks.map((t) => t.fileName));
        const todo = DEMO_TRACKS.filter((n) => !have.has(n));
        set({ progress: { total: todo.length, done: 0, current: '' } });
        try {
          for (const name of todo) {
            const id = newId();
            const { artist, title } = parseFileName(name);
            set((s) => ({ progress: { ...s.progress!, current: title } }));
            const res = await fetch(DEMO_BASE + encodeURIComponent(name));
            if (!res.ok) throw new Error(`demo ${res.status}`);
            const bytes = await res.arrayBuffer();
            await saveAudioBytes(id, bytes.slice(0));
            let track: Track = {
              id, title, artist, fileName: name, addedAt: Date.now(), analyzed: false,
              bpm: 0, firstBeat: 0, key: '', camelot: '', duration: 0,
            };
            try {
              track = { ...track, ...(await analyzeTrack(id, bytes, name)), analyzed: true };
            } catch (e) {
              console.warn('analysis failed', name, e);
            }
            set((s) => ({ tracks: [track, ...s.tracks], progress: { ...s.progress!, done: s.progress!.done + 1 } }));
          }
        } finally {
          set({ progress: null });
        }
      },

      clearCache: async () => {
        const onDecks = new Set(getEngine().decks.map((d) => d.track?.id).filter(Boolean));
        for (const t of get().tracks) {
          if (t.driveFileId && t.cached && !onDecks.has(t.id)) {
            await deleteAudioFile(t.id);
            set((s) => ({ tracks: s.tracks.map((x) => (x.id === t.id ? { ...x, cached: false } : x)) }));
          }
        }
      },
    }),
    {
      name: 'mrdj-library',
      storage: createJSONStorage(() => AsyncStorage),
      partialize: (s) => ({ tracks: s.tracks, crates: s.crates, cues: s.cues, cacheLimitMB: s.cacheLimitMB }),
    },
  ),
);

/** Wire hot-cue persistence into the audio engine once at startup. */
export function connectCuePersistence() {
  // Drive tracks may need a download before they can be decoded
  getEngine().setAudioSource(async (track) => {
    await useLibrary.getState().ensureAudio(track);
    return readAudio(track.id);
  });
  getEngine().setCuePersistence({
    get: (id) => useLibrary.getState().cues[id],
    set: (id, cues) => useLibrary.getState().setCues(id, cues),
  });
}
